-- Finance general agent demo database reset script.
-- Compatible with MySQL 8 and H2 in MySQL mode. Re-running recreates all demo tables.

DROP TABLE IF EXISTS t_audit_log;
DROP TABLE IF EXISTS t_budget;
DROP TABLE IF EXISTS t_expense;
DROP TABLE IF EXISTS t_bank_transaction;
DROP TABLE IF EXISTS t_ar_ap_record;
DROP TABLE IF EXISTS t_invoice;
DROP TABLE IF EXISTS t_voucher_entry;
DROP TABLE IF EXISTS t_voucher;
DROP TABLE IF EXISTS t_supplier;
DROP TABLE IF EXISTS t_customer;
DROP TABLE IF EXISTS t_account;

CREATE TABLE t_account (
  id BIGINT PRIMARY KEY,
  account_code VARCHAR(32) NOT NULL UNIQUE,
  account_name VARCHAR(128) NOT NULL,
  account_level INT NOT NULL,
  parent_code VARCHAR(32),
  balance_direction VARCHAR(16) NOT NULL,
  opening_balance DECIMAL(18,2) NOT NULL DEFAULT 0,
  enabled INT NOT NULL DEFAULT 1
);
CREATE TABLE t_customer (id BIGINT PRIMARY KEY, customer_code VARCHAR(32) NOT NULL UNIQUE, customer_name VARCHAR(128) NOT NULL, contact_name VARCHAR(64), contact_phone VARCHAR(32), credit_limit DECIMAL(18,2) NOT NULL DEFAULT 0);
CREATE TABLE t_supplier (id BIGINT PRIMARY KEY, supplier_code VARCHAR(32) NOT NULL UNIQUE, supplier_name VARCHAR(128) NOT NULL, contact_name VARCHAR(64), contact_phone VARCHAR(32), credit_limit DECIMAL(18,2) NOT NULL DEFAULT 0);
CREATE TABLE t_voucher (id BIGINT AUTO_INCREMENT PRIMARY KEY, voucher_no VARCHAR(64) NOT NULL UNIQUE, voucher_date DATE NOT NULL, period VARCHAR(7) NOT NULL, summary VARCHAR(255) NOT NULL, status VARCHAR(32) NOT NULL, preparer VARCHAR(64), reviewer VARCHAR(64), source_document_no VARCHAR(64));
CREATE TABLE t_voucher_entry (id BIGINT AUTO_INCREMENT PRIMARY KEY, voucher_id BIGINT NOT NULL, account_id BIGINT NOT NULL, debit_amount DECIMAL(18,2) NOT NULL DEFAULT 0, credit_amount DECIMAL(18,2) NOT NULL DEFAULT 0, remark VARCHAR(255));
CREATE TABLE t_invoice (id BIGINT AUTO_INCREMENT PRIMARY KEY, invoice_code VARCHAR(64) NOT NULL, invoice_no VARCHAR(64) NOT NULL UNIQUE, invoice_date DATE NOT NULL, invoice_type VARCHAR(32) NOT NULL, direction VARCHAR(16) NOT NULL, partner_id VARCHAR(64) NOT NULL, buyer_name VARCHAR(128), seller_name VARCHAR(128), amount DECIMAL(18,2) NOT NULL, tax_amount DECIMAL(18,2) NOT NULL, status VARCHAR(32) NOT NULL, input_status VARCHAR(32), source VARCHAR(64), file_hash VARCHAR(128));
CREATE TABLE t_ar_ap_record (id BIGINT PRIMARY KEY, record_type VARCHAR(8) NOT NULL, partner_id VARCHAR(32) NOT NULL, partner_name VARCHAR(128) NOT NULL, amount DECIMAL(18,2) NOT NULL, due_date DATE NOT NULL, status VARCHAR(32) NOT NULL);
CREATE TABLE t_bank_transaction (id BIGINT AUTO_INCREMENT PRIMARY KEY, transaction_no VARCHAR(64) NOT NULL UNIQUE, account_no VARCHAR(64) NOT NULL, transaction_date DATE NOT NULL, counterparty VARCHAR(128), summary VARCHAR(255), debit_amount DECIMAL(18,2) NOT NULL DEFAULT 0, credit_amount DECIMAL(18,2) NOT NULL DEFAULT 0, balance DECIMAL(18,2) NOT NULL DEFAULT 0, status VARCHAR(32) NOT NULL, matched_voucher_no VARCHAR(64), risk_hint VARCHAR(255));
CREATE TABLE t_expense (id BIGINT AUTO_INCREMENT PRIMARY KEY, expense_no VARCHAR(64) NOT NULL UNIQUE, employee_id VARCHAR(32) NOT NULL, employee_name VARCHAR(64) NOT NULL, department VARCHAR(64) NOT NULL, project_code VARCHAR(64), expense_type VARCHAR(64) NOT NULL, description VARCHAR(255), amount DECIMAL(18,2) NOT NULL, expense_date DATE NOT NULL, approval_status VARCHAR(32) NOT NULL, invoice_count INT NOT NULL DEFAULT 0, attachment_count INT NOT NULL DEFAULT 0, risk_hint VARCHAR(255));
CREATE TABLE t_budget (id BIGINT PRIMARY KEY, account_id BIGINT NOT NULL, department VARCHAR(64) NOT NULL, budget_year INT NOT NULL, budget_month INT NOT NULL, budget_amount DECIMAL(18,2) NOT NULL, used_amount DECIMAL(18,2) NOT NULL DEFAULT 0);
CREATE TABLE t_audit_log (
  log_id VARCHAR(64) PRIMARY KEY,
  trace_id VARCHAR(64),
  session_id VARCHAR(64),
  channel VARCHAR(32),
  corp_id VARCHAR(128),
  user_id VARCHAR(128),
  user_name VARCHAR(128),
  request_text VARCHAR(1000),
  tool_name VARCHAR(128) NOT NULL,
  service_name VARCHAR(128),
  request_args TEXT,
  response_summary TEXT,
  status VARCHAR(32) NOT NULL,
  error_message VARCHAR(1000),
  duration_ms BIGINT NOT NULL,
  occurred_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_voucher_period ON t_voucher(period);
CREATE INDEX idx_invoice_date ON t_invoice(invoice_date);
CREATE INDEX idx_ar_ap_partner ON t_ar_ap_record(partner_id);
CREATE INDEX idx_bank_account_date ON t_bank_transaction(account_no, transaction_date);
CREATE INDEX idx_audit_session ON t_audit_log(session_id);

